"""Write the Logic file (deliverable 2): how TIN -> NPI -> address was mapped, with this run's numbers."""
from __future__ import annotations

from collections import defaultdict
from pathlib import Path


def _examples(kept: list[dict], cands: list[dict], n: int = 5) -> list[str]:
    """Pairs where the runner-up site came close: the conflicts worth showing a reviewer."""
    by_pair = defaultdict(list)
    for c in cands:
        by_pair[(c["npi"], c["tin"])].append(c)
    close = []
    for key, cs in by_pair.items():
        cs = sorted(cs, key=lambda c: -c["confidence"])
        if len(cs) >= 2 and cs[0]["confidence"] > 0:
            close.append((cs[1]["confidence"] / cs[0]["confidence"], key, cs[:2]))
    out = []
    for ratio, (npi, tin), (a, b) in sorted(close, key=lambda t: -t[0])[:n]:
        out.append(f"- NPI {npi} / TIN {tin}: kept **{a['address']}** ({a['confidence']:.2f}: {a['evidence']}) "
                   f"over {b['address']} ({b['confidence']:.2f}: {b['evidence']})")
    return out


def write_logic(path: Path, cfg: dict, stats: dict, kept: list[dict], cands: list[dict]) -> None:
    w, fam = cfg["sources"]["weights"], cfg["sources"]["families"]
    tc, ag, sel, ver, pen = cfg["tin_consensus"], cfg["group_alignment"], cfg["select"], cfg["verified"], cfg["penalties"]
    rc = cfg["sources"]["recency"]
    lines = [
        "# Logic file: linking TIN -> NPI -> practice address",
        "",
        "Generated by `python -m ptd_c5 run`. The numbers below are from this run; the rules are in `config/c5.yaml`.",
        "",
        "## 1. Where each link comes from",
        "",
        "| Link | Source | Why this source |",
        "|---|---|---|",
        "| TIN <-> NPI | The Centene rate file itself (`provider_groups`: a TIN with its NPIs) | NPPES suppresses EINs, so the rate file is the only public place that pairs an NPI with the TIN it bills under. |",
        "| NPI -> candidate addresses | NPPES practice + mailing address, NPPES Practice Location Reference File, CMS Doctors & Clinicians, payer directory, NPI Registry API | Several independent sources, so they can confirm or contradict each other. |",
        "| TIN -> its sites | The TIN's roster in the rate file, intersected with every member's candidate addresses; Type 2 (organisation) NPIs under the TIN | An address many members of one TIN share is a real site of that TIN. |",
        "| NPI type, specialty | NPPES entity type and taxonomy (C6 maps taxonomy to specialty) | |",
        "",
        "## 2. Standardising addresses before comparing them",
        "",
        "Every address is standardised locally (USPS Publication 28 style): upper case, punctuation removed, "
        "street suffixes and directions abbreviated, suite/unit split into its own field, ZIP cut to 5 digits, "
        "and lines swapped when line 1 is a building name. Two addresses match when house number, street and "
        "ZIP5 match (the *site*). Suites in one building are the same site.",
        "",
        "## 3. Scoring each candidate site for one (NPI, TIN) pair",
        "",
        "**Source evidence.** Each source has a prior: the chance that its address alone is a current practice site.",
        "",
        "| Source | Weight | Family |",
        "|---|---|---|",
    ]
    fam_of = {s: f for f, ms in fam.items() for s in ms}
    lines += [f"| `{s}` | {v} | {fam_of.get(s, s)} |" for s, v in sorted(w.items(), key=lambda kv: -kv[1])]
    lines += [
        "",
        f"NPPES-based weights decay with the record's `Last Update Date`: factor = max({rc['floor']}, "
        f"0.5 ^ (age / {rc['half_life_years']} years)). Sources in one family share their data, so only the "
        "family's best counts. Families combine as independent witnesses (noisy-OR):",
        "",
        "    p_sources = 1 - prod over families (1 - best weight in the family)",
        "",
        f"**Group alignment (TIN specificity).** CMS lists an NPI once per group (`org_pac_id`). When at least "
        f"{ag['min_share']:.0%} of a TIN's NPIs in CMS share one `org_pac_id`, that group *is* the TIN: its CMS "
        f"addresses are boosted (1 - (1 - p)(1 - {ag['boost']} x share)) and the NPI's CMS addresses with other "
        f"groups, which belong to its other TINs, are discounted (p x (1 - {ag['discount']} x share)). Directory "
        "rows that carry a TIN are treated the same way.",
        "",
        f"**TIN consensus.** share = the TIN's other NPIs at this site / the TIN's other NPIs with any address, "
        "each NPI weighted by how strongly its own sources place it there (so a fresh CMS address counts more "
        f"than a 2012 NPPES one). Used for TINs with at least {tc['min_roster']} NPIs with an address. Then",
        "",
        f"    confidence = 1 - (1 - p_sources) x (1 - {tc['weight']} x share)",
        "",
        f"A site shared by at least {tc['add_site_min_share']:.0%} of the roster becomes a candidate even for a "
        "member with no address of its own (`tin_consensus_only`); a Type 1 NPI also gets the practice addresses "
        "of the Type 2 NPIs billing under the same TIN (`tin_org_site`). When the TIN clearly practises "
        f"elsewhere and none of its other NPIs share a site, that site is discounted by {tc['absent_penalty']:.0%} "
        "(it most likely belongs to the NPI's other affiliation).",
        "",
        f"**Penalties.** Outside {cfg['scope_state']}: x{pen['out_of_state']}. PO box: x{pen['po_box']}. "
        "NPIs that NPPES marks deactivated get no address" + (" (rule on)." if sel["drop_deactivated"] else " (rule off)."),
        "",
        "## 4. Conflict rules: which address is kept",
        "",
        "1. The highest-confidence site is kept as rank 1.",
        f"2. Up to {sel['max_addresses_per_pair'] - 1} more sites are kept when each reaches "
        f"{sel['secondary_min_confidence']} and at least {sel['secondary_min_ratio']:.0%} of the best "
        "(practitioners who work at several sites of the same group). Each becomes its own row in the rate file.",
        "3. Ties break on the site key, so runs are reproducible.",
        "4. When sources disagree, nothing is overruled by hand: the source weights, the family rule, group "
        "alignment and the TIN consensus decide, and the losing site stays in `c5_candidates.csv` with its score.",
        "",
        f"**Verified address** (the summary metric): at least {ver['min_families']} independent families agree on "
        "the site (TIN consensus counts as a family)"
        + (", or the payer directory lists it" if ver["directory_alone"] else "")
        + f", or its confidence is at least {ver['min_confidence']}.",
        "",
        "## 5. This run",
        "",
        "| Measure | Value |",
        "|---|---|",
    ]
    for k in ("pairs", "npis", "pairs_with_address", "pairs_with_verified_address", "npis_with_address",
              "npis_with_verified_address", "pct_npis_with_address", "pct_npis_with_verified_address",
              "address_rows", "multi_site_pairs"):
        lines.append(f"| {k.replace('_', ' ')} | {stats.get(k)} |")
    lines += ["", "Best address compared with NPPES's own practice address (the baseline the brief warns about): "
              + ", ".join(f"{k} {v:,}" for k, v in stats.get("best_address_vs_nppes_practice", {}).items())]
    lines += ["", "Sources used: " + (", ".join(f"`{k}` ({v})" for k, v in stats["sources_used"].items()) or "none"),
              "", "Best address by agreeing families:", ""]
    lines += [f"- `{k or 'none'}`: {v}" for k, v in stats["best_by_families"].items()]
    lines += ["", "Confidence of the best address:", ""]
    lines += [f"- {k}: {v}" for k, v in sorted(stats["confidence_bands"].items())]
    if stats["unresolved_reasons"]:
        lines += ["", "Unresolved pairs:", ""] + [f"- {k}: {v}" for k, v in stats["unresolved_reasons"].items()]
    ex = _examples(kept, cands)
    if ex:
        lines += ["", "## 6. Closest calls in this run", ""] + ex
    lines += ["", "## 7. Limits", "",
              "- NPPES is self-reported and often stale; it is the weakest source on purpose.",
              "- CMS Doctors & Clinicians covers only Medicare-enrolled individuals (Type 1).",
              "- The payer directory may not cover commercial PPO; when it does, it is the strongest single source.",
              "- Without a geocoder, two spellings of one street that standardise differently stay separate sites.",
              ""]
    path.write_text("\n".join(lines))
