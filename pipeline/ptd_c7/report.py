"""Write the cost-effectiveness metrics file (deliverable 3) with this run's numbers."""
from __future__ import annotations

from collections import Counter
from pathlib import Path


def write_metrics(path: Path, cfg: dict, rows: list[dict], providers: list[dict], tins: list[dict],
                  excluded: Counter, weighted: bool) -> None:
    pc = cfg["provider_score"]
    lv = Counter(r["peer_level"] for r in rows if r.get("peer_ok"))
    no_peer = sum(1 for r in rows if not r.get("peer_ok"))
    tiers = Counter(p["tier"] for p in providers)
    conf = Counter(p["score_confidence"] for p in providers)
    top = cfg["outputs"]["top_n_in_report"]
    lines = [
        "# Cost-effectiveness metrics",
        "",
        "Generated by `python -m ptd_c7 run`. Rules are in `config/c7.yaml`; numbers are from this run.",
        "",
        "## 1. What \"similar providers\" means",
        "",
        "A rate is only ever compared with rates for the **same billing code and the same price variant** "
        f"({', '.join(cfg['variant'])}). A professional office visit is never compared with a facility rate, and a "
        "per diem never with a per-service rate. Percentage-of-charges rates are left out because the charge they "
        "apply to is unknown.",
        "",
        "Within that, peers are narrowed as far as the data allows (hierarchical back-off). A rate uses the first "
        f"level whose group has at least **{cfg['min_peers']} providers**:",
        "",
    ]
    for i, lvl in enumerate(cfg["peer_levels"], start=1):
        lines.append(f"{i}. **{lvl['name']}**: same code and variant" + (f" + {', '.join(lvl['keys'])}" if lvl["keys"] else ""))
    lines += [
        "",
        "Specialty comes from C6 (NPPES taxonomy through the HiLabs crosswalk), region from C5 (county when a "
        "ZIP-county file is given, otherwise the ZIP3 market area), NPI type from NPPES. The level used is kept on "
        "every row (`peer_level`), so a reader can see how specific each comparison was.",
        "",
        "## 2. Metrics per rate (`c7_rate_benchmarks.csv.gz`)",
        "",
        "| Metric | Formula | Why |",
        "|---|---|---|",
        "| Peer median, Q1, Q3 | quantiles of the peer group's rates | The median is robust to the outliers C3 found. |",
        "| Rate index | rate / peer median | 1.00 = paid like similar providers; 0.80 = 20% cheaper. Unit-free, so codes can be combined. |",
        "| Percentile | mid-rank / (n - 1) | 0 = cheapest in the group, 1 = most expensive; ties share a rank. |",
        "| Quartile | 1-4 from the percentile | Quick read: quartile 1 is the cheapest quarter. |",
        "",
        "## 3. Metrics per provider (`c7_provider_scores.csv`, one row per NPI + TIN)",
        "",
        "| Metric | Formula | Why |",
        "|---|---|---|",
        "| Code weight w | " + ("SPEC_PROC_WEIGHT of the code in the provider's specialty (HiLabs workbook), else the code's weight across specialties" if weighted else "1 for every code (no workbook given)") + " | A provider's cost is what it costs on the services it actually does most. |",
        "| Raw cost index | exp( sum w ln(rate index) / sum w ) | Weighted geometric mean: ratios are multiplicative, so 0.5x and 2x average to 1x. |",
        "| n_eff | (sum w)^2 / sum w^2 | Effective number of codes behind the index. |",
        f"| Cost index | exp( ln(raw index) x n_eff / (n_eff + {pc['shrinkage_k']}) ) | Empirical-Bayes shrinkage: one cheap code is weak evidence, so thin providers are pulled towards 1.00. |",
        "| Cost score (0-100) | 100 x (1 - percentile of the cost index in the cohort) | 100 = cheapest of similar providers. Cohort: " + " -> ".join("+".join(c) or "everyone" for c in pc["cohort_levels"]) + f", first with {pc['min_cohort']}+ providers. |",
        "| Share in cheapest / most expensive quartile | weighted share of codes in quartile 1 / 4 | Says whether a low index is broad or driven by a few codes. |",
        "| Specialty code coverage | weight of the provider's codes / the specialty's total code weight | How much of the specialty's typical work the score covers. |",
        "| Score confidence | high: n_eff >= {h[min_n_eff]} and coverage >= {h[min_coverage]}; medium: n_eff >= {m[min_n_eff]}; else low | Tells the reader how far to trust the score. |".format(h=pc["confidence"]["high"], m=pc["confidence"]["medium"]),
        "| Tier | cost index bands: " + ", ".join(f"{t['name']} <= {t['max_index']}" if t["max_index"] else t["name"] for t in cfg["tiers"]) + " | Plain-language label. |",
        "",
        "Per TIN (`c7_tin_scores.csv`): the members' shrunk log indexes averaged with n_eff as the weight, so a "
        "group's score leans on the members with the most evidence.",
        "",
        "## 4. This run",
        "",
        f"- Rates benchmarked: {sum(lv.values()):,}; rates without {cfg['min_peers']} peers at any level (not scored): {no_peer:,}",
        "- Rates left out before benchmarking: " + (", ".join(f"{k} {v:,}" for k, v in excluded.items()) or "none"),
        "- Peer level used: " + ", ".join(f"{k} {v:,}" for k, v in lv.most_common()),
        f"- Providers scored: {len(providers):,}; TINs scored: {len(tins):,}",
        "- Tiers: " + ", ".join(f"{k} {v:,}" for k, v in tiers.most_common()),
        "- Score confidence: " + ", ".join(f"{k} {v:,}" for k, v in conf.most_common()),
        "",
    ]
    best = sorted((p for p in providers if p["score_confidence"] != "low"), key=lambda p: p["cost_index"])[:top]
    if best:
        lines += [f"### Most cost-effective providers (confidence medium or high, top {top})", "",
                  "| NPI | TIN | Specialty | Region | Cost index | Score | Codes | Tier |", "|---|---|---|---|---|---|---|---|"]
        lines += [f"| {p['npi']} | {p['tin']} | {p['specialty']} | {p['region']} | {p['cost_index']} | {p['cost_score']} | "
                  f"{p['codes_benchmarked']} | {p['tier']} |" for p in best]
        lines.append("")
    lines += ["## 5. Limits", "",
              "- Negotiated rates are not paid amounts: a cheap rate on a code a provider rarely bills matters little, "
              "which is why codes are weighted by specialty volume.",
              "- Without utilisation per provider, the weights are the specialty's typical mix, not the provider's own.",
              "- Health Net's CA file mixes PPO and HMO references; rates carry C4's network tag so the benchmark can be "
              "re-run on PPO-tagged rates only once the tagging has evidence.",
              ""]
    path.write_text("\n".join(lines))
