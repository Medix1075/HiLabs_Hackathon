"""Deliverables 2 and 3, written from a run's outputs so every number in them is this run's.

- Logic file (deliverable 2): (a) how the PPO network was identified (C2 + C4's provider tagging)
  and (b) how TIN -> NPI -> address was linked (C5's own logic file, included in full).
- File quality metrics (deliverable 3): each C3 metric, how it is calculated, why it is there,
  its weight and tolerance, and every graded file's scores with their justifications.
"""
from __future__ import annotations

import csv
import json
from collections import defaultdict
from pathlib import Path

from ptd_c3.config import load_config as load_c3_config


def _load(path: Path) -> dict:
    return json.loads(path.read_text()) if path.exists() else {}


def _rows(path: Path) -> list[dict]:
    if not path.exists():
        return []
    with open(path, newline="", encoding="utf-8-sig") as fh:
        return list(csv.DictReader(fh))


# ------------------------------------------------------------------ deliverable 2
def write_logic(out: Path) -> Path:
    c2, c4 = _load(out / "c2/c2_run_summary.json"), _load(out / "c4/c4_run_summary.json")
    conflicts = _rows(out / "c2/c2_conflicts.csv")
    files = _rows(out / "c2/c2_ppo_rate_files.csv")
    L = ["# Logic file", "",
         "Generated by `python -m ptd_run summary` from this run's outputs. Part A explains how the PPO network "
         "was identified; Part B how each TIN and NPI was linked to a practice address. Every rule and threshold "
         "named here is set in `config/c2.yaml`, `config/c4.yaml` and `config/c5.yaml`.", "",
         "# Part A: identifying the PPO network", "",
         "## A1. Scope (C2 step 1)", "",
         "A plan is in scope when it is **commercial group market**, **Health Net** (Centene's California commercial "
         "brand) and **California**. The state comes from the plan name prefix (`CA L ...`), a HIOS id, the rate "
         "file's name (`healthnet-ca` vs `healthnet-or`), or, flagged, the brand's home state. The word \"PPO\" plays "
         "no part in scope, so a PPO plan in the individual market or in Oregon is still excluded.", ""]
    if c2:
        L += [f"- Rows read from C1: {c2.get('rows')}; in scope: **{c2.get('in_scope_rows')}**.",
              f"- Excluded by rule: {c2.get('exclusions_by_rule')} (`c2_exclusions.csv` lists every row).", ""]
    L += ["## A2. Labelling each plan PPO, HMO, EPO, POS or other (C2 steps 2-6)", "",
          "Evidence is combined in a fixed priority order, strongest first:", "",
          "| Priority | Evidence | How it rules out HMO, EPO and POS |",
          "|---|---|---|",
          "| 1 | `network_name` on the rate file's provider references, mapped by rules (`PPO`, `EnhancedCare PPO` -> PPO; "
          "`HMO`, `WholeCare`, `SmartCare`, `CommunityCare`, `Salud` -> HMO; `PureCare` -> HSP; EPO; POS) | The payer's "
          "own label for the network the price belongs to. Used whenever it is filled in. |",
          "| 2 | File vote: the labels of the other plans pointing to the same rate file (>= 80% one way) | A file "
          "shared mostly by HMO plans is an HMO file. A plan never votes for itself. |",
          "| 3 | Plan name: explicit `PPO`/`HMO`/`EPO`/`POS`/`EOA` keywords and Health Net product codes (`SC`, `SAL`, "
          "`WholeCare`, `CommunityCare`, `PureCare`) | A name with two network types (e.g. PPO and EPO) is a conflict and "
          "stays UNKNOWN rather than being guessed. EOA and POS count as non-PPO. `EC` counts as EnhancedCare PPO only "
          "when no other type is present. |",
          "| 4 | Supporting signals (out-of-network file has records, capitation share) | Only adjust confidence, never "
          "the label, and only after agreeing >= 90% with network_name-confirmed plans in the same run. |", "",
          "Hypotheses (for example, reading `L&T` as a PPO hint) are tested on plans with explicit keywords and used only "
          "when they reach >= 90% precision on >= 10 plans.", ""]
    if c2:
        L += [f"- Final labels: {c2.get('final_types')}.", f"- PPO plan rows: **{c2.get('in_scope_ppo_rows')}**; "
              f"PPO rate files: **{c2.get('ppo_rate_files')}**.",
              f"- EnhancedCare PPO included: {c2.get('include_enhancedcare_ppo')}.", ""]
    if conflicts:
        kinds = defaultdict(int)
        for r in conflicts:
            kinds[r.get("conflict_type") or "conflict"] += 1
        L += ["### Conflicts and how they were handled", "",
              f"{len(conflicts)} conflicts were logged in `c2_conflicts.csv` ({dict(kinds)}). Each records both sides "
              "and the rule that decided. Unresolvable ones (e.g. a name naming both PPO and EPO) are left UNKNOWN and "
              "out of scope.", ""]
    if files:
        L += ["### The rate files that make up the PPO network", "", "| Rate file | Plans | Needs network filter |",
              "|---|---|---|"]
        for f in files[:20]:
            name = Path(f.get("rate_file_url", "")).name
            L.append(f"| {name} | {f.get('ppo_plan_rows', '')} | {f.get('needs_network_filter', '')} |")
        L.append("")
    L += ["## A3. Separating PPO providers inside a mixed file (C4)", "",
          "When PPO and HMO plans share one rate file and `network_name` is blank (Health Net CA), the file itself must "
          "be split. The unit is the **provider reference** (one TIN with its NPIs under one contract), not the NPI, "
          "because the same doctor can hold a PPO and an HMO contract at different prices.", "",
          "| Evidence | Weight | Meaning |", "|---|---|---|",
          "| network_name | 1.0 | The reference's own network label |",
          "| file label | 0.9 | C2 says the whole file is one PPO network |",
          "| payer directory | 0.9 | The reference's NPIs are listed in a PPO or non-PPO network (Plan-Net FHIR directory) |",
          "| capitation | 0.8 | The reference is paid per member per month for some services: an HMO arrangement |",
          "| dual contract (hypothesis) | 0.5 | One TIN in two references with mostly the same NPIs at different prices: the higher-paid one is PPO |",
          "| label spreading (hypothesis) | spread | References priced together for the same codes share a contract |",
          "", "A reference is tagged PPO or NON_PPO when one side holds >= 65% of its evidence, otherwise UNKNOWN. "
          "Hypotheses are used only after passing a held-out test (precision >= 0.9 on >= 10 pairs; 5-fold accuracy "
          ">= 0.9). **PPO and UNKNOWN references are kept, NON_PPO are dropped**, so no rate is thrown away without "
          "evidence; every row carries its tag and confidence.", ""]
    for url, rep in (c4.get("network") or {}).items():
        L += [f"**{Path(url).name}**: {rep.get('references')} references. Evidence found: {rep.get('seeded_by')}. "
              f"Dual-contract hypothesis: {rep.get('dual_contract')}. Label spreading: {rep.get('propagation')}. "
              f"Result: {rep.get('tags')}.", ""]
    if c4 and not c4.get("directory"):
        L += ["No payer directory was available in this run, so PPO membership could not be confirmed. References "
              "without capitation stay UNKNOWN and are kept. A directory (`python -m ptd_c4 directory`) is the input "
              "that would close this gap.", ""]
    L += ["# Part B: linking TIN -> NPI -> address", ""]
    c5_logic = out / "c5/c5_logic.md"
    if c5_logic.exists():
        body = c5_logic.read_text().splitlines()
        body = [("#" + ln if ln.startswith("#") else ln) for ln in body[1:]]  # one level down under Part B
        L += body
    else:
        L.append("C5 has not been run, so there is no address logic for this run yet.")
    path = out / "logic.md"
    path.write_text("\n".join(L) + "\n")
    return path


# ------------------------------------------------------------------ deliverable 3
METRICS = {
    "schema_validity": ("Problems per record against the CMS in-network schema v2.0.0: required fields, allowed values "
                        "(negotiation_arrangement, negotiated_type, billing_class, setting, TIN type, code type), code "
                        "formats, date format, references to undefined provider groups, blank network_name. Halved if a "
                        "top-level field is missing.",
                        "A file that breaks the schema can't be parsed reliably, and every later number inherits the "
                        "error. Blank network_name is counted because it hides which network a price belongs to."),
    "code_coverage": ("Share of the HiLabs benchmark codes present in the file, each code weighted by its specialty's "
                      "weight times its share of that specialty's code volume.",
                      "A file is only useful for benchmarking if it prices the services that matter. Missing 99214 "
                      "costs far more than missing a rare code, so the share is weighted by volume."),
    "provider_coverage": ("Share of price rows tied to at least one provider group with a valid NPI (10 digits and "
                          "a correct Luhn check digit).",
                          "A rate with no valid provider can't be attributed to anyone, so it is useless for "
                          "contracting."),
    "zero_rates": ("Share of price rows with a rate of 0 or less.",
                   "$0 rates are placeholders, not prices, and would drag every benchmark down."),
    "outliers": ("Share of rates outside a log-IQR fence (k = 3) AND at least 3x away from the median of the same "
                 "code, rate type, billing class, setting and modifiers; percentages above 100.",
                 "Both conditions must hold, so legitimately different prices (facility vs office) are never "
                 "compared, and a skewed but real distribution isn't punished."),
    "rate_type_mix": ("Share of rows that are dollar amounts comparable across providers (negotiated, fee schedule, "
                      "derived), as opposed to percentages of charges or per diems.",
                      "Percentage-of-charges rates can't be compared without the charge, so a file made of them "
                      "supports less analysis."),
    "duplicates": ("Share of rows that exactly repeat an earlier row (same code, providers, type, rate, class, "
                   "setting, service codes, modifiers, expiry).",
                   "Exact repeats inflate counts and weights and signal a careless export."),
    "staleness": ("Average of the expired-row score (rows past their expiration date; 9999-12-31 is evergreen) and "
                  "a file-age score from last_updated_on (1 within 45 days, 0 at 365).",
                  "Contracts change; an expired rate or an old file no longer says what the payer pays today."),
    "junk": ("TIN-only provider groups (no NPI), placeholder TINs (999999999...), NPIs failing the check digit, and "
             "rows on catch-all codes (CSTM-ALL).",
             "These rows can't be linked to a real provider or a real service."),
}


def write_quality_metrics(out: Path) -> Path:
    cfg = load_c3_config()
    tol, weights = cfg["tolerance"], cfg["weights"]
    tol_of = {"schema_validity": "schema_error_share", "zero_rates": "zero_rate_share", "outliers": "outlier_share",
              "duplicates": "duplicate_share", "junk": "junk_group_share"}
    L = ["# File quality metrics", "",
         "Generated by `python -m ptd_run summary`. Weights and tolerances come from `config/c3.yaml`; the scores are "
         "from this run (`out/c3/`).", "",
         "## How a file is scored", "",
         "Each rate file is read once, start to end, without loading it whole. Each metric gives a 0-1 score. "
         "\"Share of bad rows\" metrics score `1 - min(1, share / tolerance)`, so a share at or above the tolerance "
         "scores 0. The file's score is the weighted mean of the metrics that could be measured, on a 0-100 scale, "
         f"graded {', '.join(f'{k} >= {v}' for k, v in cfg['grades'].items())}, otherwise F. A metric that can't be "
         "measured (e.g. code coverage without the workbook) is left out and the other weights are rescaled; the "
         "output says so.", "",
         "## The metrics", "",
         "| Metric | Weight | Tolerance | How it is calculated | Why it matters |", "|---|---|---|---|---|"]
    for m, (how, why) in METRICS.items():
        t = tol.get(tol_of.get(m, ""), "")
        L.append(f"| `{m}` | {weights.get(m, '')} | {f'{t:.0%}' if isinstance(t, float) else '-'} | {how} | {why} |")
    scores = _rows(out / "c3/c3_file_scores.csv")
    metrics = _rows(out / "c3/c3_metrics.csv")
    if scores:
        L += ["", "## Scores in this run", "", "| File | Bucket | Score | Grade | Status |", "|---|---|---|---|---|"]
        for s in scores:
            L.append(f"| {Path(s.get('rate_file_url', '')).name} | {s.get('bucket', '')} | {s.get('score', '')} | "
                     f"{s.get('grade', '')} | {s.get('status', '')} |")
        by_file = defaultdict(list)
        for m in metrics:
            by_file[(m.get("rate_file_url", ""), m.get("bucket", ""))].append(m)
        for (url, bucket), ms in by_file.items():
            L += ["", f"### {Path(url).name} ({bucket})", "", "| Metric | Value | Score | Justification |",
                  "|---|---|---|---|"]
            for m in ms:
                just = (m.get("justification") or "").replace("|", "/")
                L.append(f"| `{m.get('metric')}` | {m.get('value')} | {m.get('score') or 'not measured'} | {just} |")
        L += ["", "Example rows behind each issue are in `out/c3/c3_examples.csv`; schema problems by type in "
              "`out/c3/c3_schema_problems.csv`."]
    else:
        L += ["", "C3 has not been run, so there are no scores yet."]
    path = out / "file_quality_metrics.md"
    path.write_text("\n".join(L) + "\n")
    return path
