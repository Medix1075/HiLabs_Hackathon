METRICS = {
    "schema_validity": ("Problems per record against the CMS in-network schema v2.0.0: required fields, allowed values "
                        "(negotiation_arrangement, negotiated_type, billing_class, setting, TIN type, code type), code "
                        "formats, date format, references to undefined provider groups, blank network_name. Halved if a "
                        "top-level field is missing.",
                        "A file that breaks the schema can't be parsed reliably, and every later number inherits the "
                        "error. Blank network_name is counted because it hides which network a price belongs to."),
    "code_coverage": ("Share of the HiLabs benchmark codes present in the file, each code weighted by its specialty's "
                      "weight times its share of that specialty's code volume.",
                      "A file is only useful for benchmarking if it prices the services that matter. Missing 99214 "
                      "costs far more than missing a rare code, so the share is weighted by volume."),
    "provider_coverage": ("Share of price rows tied to at least one provider group with a valid NPI (10 digits and "
                          "a correct Luhn check digit).",
                          "A rate with no valid provider can't be attributed to anyone, so it is useless for "
                          "contracting."),
    "zero_rates": ("Share of price rows with a rate of 0 or less.",
                   "$0 rates are placeholders, not prices, and would drag every benchmark down."),
    "outliers": ("Share of rates outside a log-IQR fence (k = 3) AND at least 3x away from the median of the same "
                 "code, rate type, billing class, setting and modifiers; percentages above 100.",
                 "Both conditions must hold, so legitimately different prices (facility vs office) are never "
                 "compared, and a skewed but real distribution isn't punished."),
    "rate_type_mix": ("Share of rows that are dollar amounts comparable across providers (negotiated, fee schedule, "
                      "derived), as opposed to percentages of charges or per diems.",
                      "Percentage-of-charges rates can't be compared without the charge, so a file made of them "
                      "supports less analysis."),
    "duplicates": ("Share of rows that exactly repeat an earlier row (same code, providers, type, rate, class, "
                   "setting, service codes, modifiers, expiry).",
                   "Exact repeats inflate counts and weights and signal a careless export."),
    "staleness": ("Average of the expired-row score (rows past their expiration date; 9999-12-31 is evergreen) and "
                  "a file-age score from last_updated_on (1 within 45 days, 0 at 365).",
                  "Contracts change; an expired rate or an old file no longer says what the payer pays today."),
    "junk": ("TIN-only provider groups (no NPI), placeholder TINs (999999999...), NPIs failing the check digit, and "
             "rows on catch-all codes (CSTM-ALL).",
             "These rows can't be linked to a real provider or a real service."),
}


def write_quality_metrics(out: Path) -> Path:
    cfg = load_c3_config()
    tol, weights = cfg["tolerance"], cfg["weights"]
    tol_of = {"schema_validity": "schema_error_share", "zero_rates": "zero_rate_share", "outliers": "outlier_share",
              "duplicates": "duplicate_share", "junk": "junk_group_share"}
    L = ["# File quality metrics", "",
         "Generated by `python -m ptd_run summary`. Weights and tolerances come from `config/c3.yaml`; the scores are "
         "from this run (`out/c3/`).", "",
         "## How a file is scored", "",
         "Each rate file is read once, start to end, without loading it whole. Each metric gives a 0-1 score. "
         "\"Share of bad rows\" metrics score `1 - min(1, share / tolerance)`, so a share at or above the tolerance "
         "scores 0. The file's score is the weighted mean of the metrics that could be measured, on a 0-100 scale, "
         f"graded {', '.join(f'{k} >= {v}' for k, v in cfg['grades'].items())}, otherwise F. A metric that can't be "
         "measured (e.g. code coverage without the workbook) is left out and the other weights are rescaled; the "
         "output says so.", "",
         "## The metrics", "",
         "| Metric | Weight | Tolerance | How it is calculated | Why it matters |", "|---|---|---|---|---|"]
    for m, (how, why) in METRICS.items():
        t = tol.get(tol_of.get(m, ""), "")
        L.append(f"| `{m}` | {weights.get(m, '')} | {f'{t:.0%}' if isinstance(t, float) else '-'} | {how} | {why} |")
    scores = _rows(out / "c3/c3_file_scores.csv")
    metrics = _rows(out / "c3/c3_metrics.csv")
    if scores:
        L += ["", "## Scores in this run", "", "| File | Bucket | Score | Grade | Status |", "|---|---|---|---|---|"]
        for s in scores:
            L.append(f"| {Path(s.get('rate_file_url', '')).name} | {s.get('bucket', '')} | {s.get('score', '')} | "
                     f"{s.get('grade', '')} | {s.get('status', '')} |")
        by_file = defaultdict(list)
        for m in metrics:
            by_file[(m.get("rate_file_url", ""), m.get("bucket", ""))].append(m)
        for (url, bucket), ms in by_file.items():
            L += ["", f"### {Path(url).name} ({bucket})", "", "| Metric | Value | Score | Justification |",
                  "|---|---|---|---|"]
            for m in ms:
                just = (m.get("justification") or "").replace("|", "/")
                L.append(f"| `{m.get('metric')}` | {m.get('value')} | {m.get('score') or 'not measured'} | {just} |")
        L += ["", "Example rows behind each issue are in `out/c3/c3_examples.csv`; schema problems by type in "
              "`out/c3/c3_schema_problems.csv`."]
    else:
        L += ["", "C3 has not been run, so there are no scores yet."]
    path = out / "file_quality_metrics.md"
    path.write_text("\n".join(L) + "\n")
    return path
